// Regenerates src/data/baseCatalog.js from the built-in CATALOG (single source of truth for the shape).
// Usage: node scripts/gen-base-catalog.mjs
// It is the OFFLINE price layer: when a material has neither a price of the user nor a live one, the app reads this.
// It is a plain ES module (NOT a .json import): Node's native ESM (Vercel serverless functions) refuses JSON imports without
// an import attribute, while Vite, Vitest and Node all load a .js module the same way.
import fs from 'node:fs';
import { CATALOG } from '../src/lib/catalog.js';

const items = {};
for (const [id, m] of Object.entries(CATALOG)) {
  items[id] = { sale: m.sale, size: Math.round(m.size * 1e4) / 1e4, usd: m.usd };
}
const out = { version: 1, currency: 'USD', note: 'Reference price of ONE sale unit before regional index and chain factor.', items };
const source = `// GENERATED by scripts/gen-base-catalog.mjs - edit the in-code CATALOG and regenerate. A .js module on purpose (see the script).\nexport default ${JSON.stringify(out, null, 1)};\n`;
fs.writeFileSync(new URL('../src/data/baseCatalog.js', import.meta.url), source);
console.log(`baseCatalog.js: ${Object.keys(items).length} items`);
