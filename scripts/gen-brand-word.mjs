// Generates src/brand/wordArt.js: the CUBRAX lettering as outlines of Montserrat SemiBold (SIL OFL 1.1), so the app
// needs no font at run time and the letters look identical everywhere.
//
//   npm i --no-save opentype.js @fontsource/montserrat   (dev tools, NOT app dependencies)
//   node scripts/gen-brand-word.mjs [weight=600]
//
// The hard hat is NOT generated: it is the supplied photoreal artwork (public/helmet.png, see scripts/prep-helmet.mjs).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const opentype = require('opentype.js');
const WEIGHT = Number(process.argv[2] || 600);
if (![500, 600].includes(WEIGHT)) throw new Error('use Medium (500) or SemiBold (600)');
const fontFile = require.resolve(`@fontsource/montserrat/files/montserrat-latin-${WEIGHT}-normal.woff`);

const raw = fs.readFileSync(fontFile);
const font = opentype.parse(raw.buffer.slice(raw.byteOffset, raw.byteOffset + raw.byteLength));
const SIZE = 100;
const TRACK = 12; // airy, technical spacing
let penX = 0;
const letters = [];
for (const ch of 'CUBRAX') {
  const g = font.charToGlyph(ch);
  letters.push({ ch, d: g.getPath(penX, 0, SIZE).toPathData(1) });
  penX += (g.advanceWidth * SIZE) / font.unitsPerEm + TRACK;
}
const capH = (font.tables.os2.sCapHeight * SIZE) / font.unitsPerEm;
const box = { x: 0, y: -Math.ceil(capH) - 1, w: Math.ceil(penX - TRACK) + 1, h: Math.ceil(capH) + 2 };

const out = `// GENERATED by scripts/gen-brand-word.mjs. Do not edit by hand: change the generator and run it again.
// CUBRAX lettering: Montserrat ${WEIGHT === 500 ? 'Medium (500)' : 'SemiBold (600)'} outlines (SIL OFL 1.1).

export const WORD = 'CUBRAX';
export const WORD_WEIGHT = ${WEIGHT};
export const LETTER_PATHS = Object.freeze(${JSON.stringify(Object.fromEntries(letters.map((l) => [l.ch, l.d])), null, 2)});
export const WORD_BOX = Object.freeze(${JSON.stringify(box)});
`;
fs.writeFileSync(path.join(here, '../src/brand/wordArt.js'), out);
console.log('wordArt.js written', WEIGHT, box);
