// Single source of truth for the brand icon.
// Used by: <Logo/>, favicon, manifest icons (SVG + PNG 192/512 + maskable) and apple-touch-icon.
// This file must stay free of browser/node-only imports (it is imported by the Vite plugin too).

export const BRAND = Object.freeze({
  name: 'CUBRAX',
  shortName: 'CUBRAX',
  appId: 'com.obrax.app',
  title: 'CUBRAX - Cubicación & Presupuestos de Obra',
  description:
    'Cubicación, materiales y presupuestos de obra para profesionales de la construcción. Funciona sin conexión.',
  green: '#22c55e',
  black: '#000000',
});

// ---- the isotype: THREE LEVELS, one precise composition (hybrid: static SVG + supplied photoreal asset) -----------
//   top     architectural dimension line (static SVG), exactly as wide as the hat
//   centre  the hard hat: the supplied photoreal artwork, public/helmet.png, drawn as an <img> / <image> with
//           object-fit: contain (preserveAspectRatio meet), so its volume and proportions are never touched
//   bottom  graduated ruler with its green hook (static SVG), separated from the hat by clean transparent air
// The hat is no longer drawn or generated by code. Everything is laid out in the units of MARK_LAYOUT.
import { WORD, LETTER_PATHS, WORD_BOX } from './wordArt.js';
export { WORD, LETTER_PATHS, WORD_BOX };

/** The supplied hard hat (transparent PNG prepared by scripts/prep-helmet.mjs from design/logo-source.jpg). */
export const HELMET_FILE = 'helmet.png';
export const HELMET_RATIO = 1.3417; // width / height of helmet.png (checked by the brand tests)

const W = 360; // width of the whole isotype = width of the hat = width of the dimension line
const DIM_H = 28;
const GAP_TOP = 26; // transparent air between the dimension line and the hat   (14-30 required)
const HELMET_H = Math.round(W / HELMET_RATIO); // 272
const GAP_BOTTOM = 28; // transparent air between the hat and the ruler           (14-30 required)
const RULER_H = 60; // hook height (the ruler body is a little shorter)

export const MARK_LAYOUT = Object.freeze({
  w: W,
  h: DIM_H + GAP_TOP + HELMET_H + GAP_BOTTOM + RULER_H,
  dimension: Object.freeze({ y: 0, h: DIM_H }),
  gapTop: GAP_TOP,
  helmet: Object.freeze({ y: DIM_H + GAP_TOP, h: HELMET_H }),
  gapBottom: GAP_BOTTOM,
  ruler: Object.freeze({ y: DIM_H + GAP_TOP + HELMET_H + GAP_BOTTOM, h: RULER_H }),
});
export const MARK_RATIO = MARK_LAYOUT.h / MARK_LAYOUT.w; // height / width

const INK = '#ffffff';
/** Level 1: dimension line with end ticks and arrowheads. Coordinates are in the isotype's own units. */
export const DIM_ART =
  `<g fill="none" stroke="${INK}" stroke-width="7" stroke-linecap="round" stroke-linejoin="round">` +
  `<path d="M6 14H354M6 2V26M354 2V26M30 5L6 14L30 23M330 5L354 14L330 23"/></g>`;

/** Level 3: ruler (white body, 19 black graduations, green hook). */
export const RULER_ART = (() => {
  const { y } = MARK_LAYOUT.ruler;
  const body = y + 8;
  const x0 = 28;
  const step = (354 - x0 - 14) / 18;
  let ticks = '';
  for (let i = 0; i <= 18; i += 1) ticks += `M${(x0 + 12 + i * (step - 0.45)).toFixed(1)} ${body}V${body + (i % 3 === 0 ? 24 : 14)}`;
  return (
    `<rect x="22" y="${body}" width="332" height="44" rx="5" fill="${INK}"/>` +
    `<path d="${ticks}" stroke="#000000" stroke-width="3.6"/>` +
    `<rect x="6" y="${y}" width="16" height="${RULER_H}" rx="4" fill="${'#22c55e'}"/>`
  );
})();

/** The hat as an SVG <image> (meet = object-fit: contain) placed in its own level. */
export const helmetImage = (href = `./${HELMET_FILE}`) =>
  `<image href="${href}" x="0" y="${MARK_LAYOUT.helmet.y}" width="${W}" height="${HELMET_H}" preserveAspectRatio="xMidYMid meet"/>`;

/** Complete isotype on transparent background. `helmetHref` is a data URI when the SVG must be self-contained. */
export function buildMarkSvg({ helmetHref } = {}) {
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${MARK_LAYOUT.h}" width="${W}" height="${MARK_LAYOUT.h}" role="img" aria-label="CUBRAX">` +
    DIM_ART +
    helmetImage(helmetHref) +
    RULER_ART +
    '</svg>'
  );
}

// ---- the wordmark: geometric sans (Montserrat SemiBold outlines), white, with the X in brand green ---------------
export const wordmarkInner = (ink = '#ffffff') => [...WORD].map((c) => `<path d="${LETTER_PATHS[c]}" fill="${c === 'X' ? BRAND.green : ink}"/>`).join('');
export const WORD_VIEWBOX = `${WORD_BOX.x} ${WORD_BOX.y} ${WORD_BOX.w} ${WORD_BOX.h}`;

/** The isotype nested at a position/scale inside a larger SVG. */
const nestedMark = (cx, top, k, helmetHref) =>
  `<svg x="${cx - (W * k) / 2}" y="${top}" width="${W * k}" height="${MARK_LAYOUT.h * k}" viewBox="0 0 ${W} ${MARK_LAYOUT.h}">` +
  DIM_ART + helmetImage(helmetHref) + RULER_ART + '</svg>';

/** Complete lockup on black: isotype, CUBRAX, "Un producto Japadigital" (1024 x 1024, exported as /logo.png). */
export function buildLockupSvg({ helmetHref } = {}) {
  const k = 1.15;
  const ws = 1.4;
  return (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024" role="img" aria-label="CUBRAX">' +
    '<rect width="1024" height="1024" fill="#000000"/>' +
    nestedMark(512, 70, k, helmetHref) +
    `<g transform="translate(${512 - (WORD_BOX.w * ws) / 2} 718) scale(${ws})">${wordmarkInner()}</g>` +
    '<text x="512" y="850" text-anchor="middle" fill="#a3a3a3" font-family="system-ui,Segoe UI,Roboto,sans-serif" font-size="38" letter-spacing="2">Un producto Japadigital</text>' +
    '</svg>'
  );
}

/**
 * App icon: the isotype centred on an OLED-black rounded tile.
 * @param {{maskable?: boolean, helmetHref?: string}} opts maskable => full-bleed background, content scaled into the safe zone.
 */
export function buildIconSvg({ maskable = false, helmetHref } = {}) {
  const k = maskable ? 0.74 : 0.9;
  const art = nestedMark(256, 256 - (MARK_LAYOUT.h * k) / 2, k, helmetHref);
  return (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512" role="img" aria-label="CUBRAX">' +
    `<rect width="512" height="512" rx="${maskable ? 0 : 112}" fill="#000000"/>` +
    '<rect x="6" y="6" width="500" height="500" rx="106" fill="none" stroke="#22c55e" stroke-width="4" stroke-opacity=".45"' +
    (maskable ? ' display="none"' : '') +
    '/>' +
    art +
    '</svg>'
  );
}

